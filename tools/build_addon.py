"""Builds the WoW addon into addon/dist/FlightPathRaiders/ (copy that folder into
World of Warcraft/_forever_/Interface/AddOns/). The engine files are copied unchanged, so the addon
runs exactly the code every test checks. Usage: python3 tools/build_addon.py"""
import os, shutil, re
ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "addon/dist/FlightPathRaiders")
ENGINE = ["engine/rng.lua", "engine/data.lua", "engine/sim.lua", "engine/validate.lua", "engine/progress.lua", "engine/game.lua"]
TESTS = ["tests/fixtures.lua", "tests/selftest.lua"]
SRC = ["addon/src/Core.lua", "addon/src/SelfTest.lua", "addon/src/UI.lua", "addon/src/Board.lua", "addon/src/Pages.lua", "addon/src/Raid.lua"]
version = re.search(r"ENGINE_VERSION = (\d+)", open(os.path.join(ROOT, "engine/sim.lua")).read()).group(1)
shutil.rmtree(OUT, ignore_errors=True)
for sub in ("Engine", "Test"): os.makedirs(os.path.join(OUT, sub))
files = []
for f in ENGINE: shutil.copy(os.path.join(ROOT, f), os.path.join(OUT, "Engine", os.path.basename(f))); files.append("Engine\\" + os.path.basename(f))
for f in TESTS: shutil.copy(os.path.join(ROOT, f), os.path.join(OUT, "Test", os.path.basename(f))); files.append("Test\\" + os.path.basename(f))
golden = open(os.path.join(ROOT, "tests/golden.txt")).read().rstrip("\n")
open(os.path.join(OUT, "Test", "Golden.lua"), "w").write(
    "-- Generated by tools/build_addon.py from tests/golden.txt. Do not edit.\nlocal _, ns = ...\nns.GOLDEN = [==[\n" + golden + "]==]\n")
files.append("Test\\Golden.lua")
import sys; sys.path.insert(0, os.path.dirname(__file__))
from addon_media import export
textures = export(OUT); files.append("Media.lua")
for f in SRC: shutil.copy(os.path.join(ROOT, f), os.path.join(OUT, os.path.basename(f))); files.append(os.path.basename(f))
toc = f"""## Interface: 16001
## Title: Flight Path Raiders
## Notes: Run a 10-player raid team on your flight paths.
## Author: Bubbi
## Version: 0.4.0-slice (engine {version})
## SavedVariables: FlightPathRaidersDB

""" + "\n".join(files) + "\n"
open(os.path.join(OUT, "FlightPathRaiders.toc"), "w").write(toc)
print("built", os.path.relpath(OUT, ROOT), "with", len(files), "Lua files and", len(textures), "textures, engine", version)
